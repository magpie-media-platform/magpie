namespace Magpie.Models.Enums;

/// <summary>
/// The data type of a parameter.
/// </summary>
public enum DataType
{
    /// <summary>
    /// Represents a string value.
    /// </summary>
    String = 0,

    /// <summary>
    /// Represents a numeric value.
    /// </summary>
    Number,

    /// <summary>
    /// Represents a boolean value.
    /// </summary>
    Boolean,

    /// <summary>
    /// Represents a Date value
    /// </summary>
    Date
}
